// ─── Helper Functions ─────────────────────────────────────────────────────────

export function getBuahLimbahList(): BuahLimbahBuahItem[] {
  return BUAH_LIMBAH_BUAH_DB;
}

export function getBuahLimbahById(id: string): BuahLimbahBuahItem | undefined {
  return BUAH_LIMBAH_BUAH_DB.find(item => item.id === id);
}

export interface BuahLimbahRingkasan {
  totalReferensi: number;
  hargaRataRata: number | null;
  terakhirUpdate: string;
  dataLengkap: number;
}

export function computeBuahLimbahRingkasan(): BuahLimbahRingkasan {
  const items = BUAH_LIMBAH_BUAH_DB;
  const priced = items.filter(i => i.estimasiHarga !== null);
  const hargaRataRata =
    priced.length > 0
      ? Math.round(priced.reduce((sum, i) => sum + i.estimasiHarga!, 0) / priced.length)
      : null;

  // Most recent updatedAt
  const dates = items.map(i => i.updatedAt).sort().reverse();
  const terakhirUpdate = dates[0] ?? '—';

  return {
    totalReferensi: items.length,
    hargaRataRata,
    terakhirUpdate,
    dataLengkap: items.filter(i => i.dataLengkap).length,
  };
}
