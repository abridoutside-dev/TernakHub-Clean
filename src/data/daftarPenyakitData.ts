// ─── Lookup Functions ─────────────────────────────────────────────────────────

export function getPenyakitByKategori(kategoriSlug: string): PenyakitListItem[] {
  return DAFTAR_PENYAKIT.filter((p) => p.kategoriSlug === kategoriSlug);
}

/**
 * SP-005: Daftar penyakit untuk kombinasi kategori + jenis ternak tertentu.
 * Digunakan agar setiap jenis ternak hanya menampilkan penyakit yang relevan
 * untuknya di dalam sebuah kategori (bukan seluruh penyakit kategori tersebut).
 */
export function getPenyakitByKategoriDanTernak(
  kategoriSlug: string,
  ternakSlug: string,
): PenyakitListItem[] {
  return DAFTAR_PENYAKIT.filter(
    (p) => p.kategoriSlug === kategoriSlug && p.jenisTernak.includes(ternakSlug),
  );
}

export function getPenyakitByUuid(uuid: string): PenyakitListItem | undefined {
  return DAFTAR_PENYAKIT.find((p) => p.uuid === uuid);
}

export function getAllPenyakit(): PenyakitListItem[] {
  return DAFTAR_PENYAKIT;
}
