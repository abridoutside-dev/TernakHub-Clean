// ─── Filter Function ──────────────────────────────────────────────────────────

export interface ListingFilterParams {
  title?: string;
  listingId?: string;
  seller?: string;
  livestockId?: string;
  category?: ListingCategory | 'All';
  species?: LivestockSpecies | 'All';
  status?: ListingStatus | 'All';
  verification?: VerificationStatus | 'All';
  dateFrom?: string;
  dateTo?: string;
}

export function filterListings(
  list: AdminListingRecord[],
  p: ListingFilterParams,
): AdminListingRecord[] {
  return list.filter((item) => {
    if (p.title && !item.title.toLowerCase().includes(p.title.toLowerCase())) return false;
    if (p.listingId && !item.id.toLowerCase().includes(p.listingId.toLowerCase())) return false;
    if (p.seller && !item.sellerName.toLowerCase().includes(p.seller.toLowerCase())) return false;
    if (p.livestockId && item.livestockId && !item.livestockId.toLowerCase().includes(p.livestockId.toLowerCase())) return false;
    if (p.livestockId && !item.livestockId) return false;
    if (p.category && p.category !== 'All' && item.category !== p.category) return false;
    if (p.species && p.species !== 'All' && item.species !== p.species) return false;
    if (p.status && p.status !== 'All' && item.status !== p.status) return false;
    if (p.verification && p.verification !== 'All' && item.verification !== p.verification) return false;
    return true;
  });
}
