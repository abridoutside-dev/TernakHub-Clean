//   audit log       → Global Audit Trail Service
//   activity log    → Global Activity Service
//   search index    → Global Search Service
//   entity_uuid     → Livestock / Feed / Medicine / Marketplace / Transaction
// ─────────────────────────────────────────────────────────────────────────────

