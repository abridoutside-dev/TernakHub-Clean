// ─── In-Memory Store ──────────────────────────────────────────────────────────
// INTERNAL — akses hanya melalui globalAiInsightService.ts.

export const GLOBAL_AI_INSIGHT_DB: Map<string, AiInsightRecord> = new Map();

// ─── Internal Helpers (package-private) ───────────────────────────────────────

export function _insertInsight(record: AiInsightRecord): void {
  GLOBAL_AI_INSIGHT_DB.set(record.insight_uuid, record);
}

export function _replaceInsight(record: AiInsightRecord): void {
  GLOBAL_AI_INSIGHT_DB.set(record.insight_uuid, record);
}

export function _getAllInsights(): AiInsightRecord[] {
  return Array.from(GLOBAL_AI_INSIGHT_DB.values());
}

