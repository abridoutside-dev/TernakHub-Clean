// ─── Schema — AiInsightRecord ─────────────────────────────────────────────────

export interface AiInsightRecord {
  /** UUID v4 — primary key. Immutable setelah ditetapkan. */
  insight_uuid: string;

  /**
   * Jenis insight — UUID ke INSIGHT_TYPE di Global Reference.
   * Gunakan INSIGHT_TYPE_UUID untuk referensi stabil.
   */
  insight_type_reference_uuid: string;

  /**
   * Status siklus hidup — UUID ke INSIGHT_STATUS.
   * Gunakan INSIGHT_STATUS_UUID untuk referensi stabil.
   */
  insight_status_reference_uuid: string;

  /**
   * Tingkat prioritas — UUID ke PRIORITY di Global Reference (FOUNDATION-007).
   * Gunakan INSIGHT_PRIORITY_UUID untuk referensi stabil.
   * Default: Normal.
   */
  priority_reference_uuid: string;

  /**
   * Workspace yang menerima insight ini.
   * null = insight global/sistem yang tidak terikat workspace.
   */
  workspace_uuid: string | null;

  /**
   * Jenis entity yang menjadi subjek insight — UUID ke ENTITY_TYPE.
   * null = insight lintas entity atau sistem.
   */
  entity_type_reference_uuid: string | null;

  /**
   * UUID entity yang menjadi subjek insight.
   * Contoh: livestock.id, batch_uuid, listing_uuid.
   * null = insight tidak merujuk entitas spesifik.
   */
  entity_uuid: string | null;

  /**
   * Judul singkat insight untuk tampilan.
   * Contoh: 'ADG di Bawah Target', 'Stok Pakan Kritis'.
   * Maks 200 karakter. Wajib diisi.
   */
  title: string;

  /**
   * Ringkasan satu-dua kalimat untuk tampilan kompak.
   * Contoh: 'ADG 180g/hari — 28% di bawah target 250g/hari selama 14 hari.'.
   * Wajib diisi.
   */
  summary: string;

  /**
   * Penjelasan lengkap insight — data, tren, dan konteks yang mendasari.
   * null = summary sudah cukup.
   */
  description: string | null;

  /**
   * Rekomendasi tindakan yang dapat dilakukan pengguna.
   * null = insight bersifat informatif tanpa rekomendasi spesifik.
   */
  recommendation: string | null;

  /**
   * Tingkat keyakinan sistem terhadap insight (0.00–1.00).
   * 1.00 = pasti (rule-based dengan data lengkap).
   * < 0.5 = tidak cukup data untuk kesimpulan yang kuat.
   * null = belum dihitung.
   */
  confidence_score: number | null;

  /**
   * Skor kualitas evidence yang mendukung insight (0–100).
   * Berasal dari Global Evidence Service — belum di-wire.
   * null = tidak ada evidence spesifik.
   */
  evidence_score: number | null;

  /** Mekanisme yang menghasilkan insight. */
  generated_by: InsightGeneratedBy;

  /** Modul yang menghasilkan insight. */
  source_module: InsightSourceModule;

  /**
   * Timestamp ISO 8601 kapan insight ini dihasilkan (bisa berbeda dari created_at
   * jika insight di-backfill atau di-import).
   */
  generated_at: string;

  /**
   * Timestamp ISO 8601 kapan insight ini kedaluwarsa.
   * null = tidak ada masa berlaku (insight permanen sampai diarsipkan secara eksplisit).
   */
  expired_at: string | null;

  /** Timestamp ISO 8601 saat record pertama dibuat. */
  created_at: string;

  /** Timestamp ISO 8601 saat record terakhir diperbarui. */
  updated_at: string;
}

