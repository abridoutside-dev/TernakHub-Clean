// ATURAN:
//   • Semua modul menghasilkan insight HANYA melalui globalAiInsightService.ts.
//   • Akses langsung ke GLOBAL_AI_INSIGHT_DB atau fungsi _* dilarang dari luar.
//   • Engine ini TIDAK melakukan AI inference — ia menjadi pusat penyimpanan,
//     manajemen, dan distribusi insight yang dihasilkan oleh modul lain.
//   • Insight HARUS explainable, evidence-based, dan data-driven.
//   • AI TIDAK boleh membuat kesimpulan tanpa evidence.
//   • insight_type, insight_status, priority, entity_type HARUS menggunakan UUID
//     dari Global Reference Service.
//   • UUID bersifat stabil — jangan diregenerasi setelah ditetapkan.
